// Escape regex special characters safely
function escapeRegex(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

// Build exact word-boundary regex for a given phrase
function buildPhraseRegex(phrase) {
  const escaped = escapeRegex(phrase)
  const startsWithWordChar = /^\w/.test(phrase)
  const endsWithWordChar = /\w$/.test(phrase)

  const leftBoundary = startsWithWordChar ? '\\b' : '(?:^|\\s|[^\\w])'
  const rightBoundary = endsWithWordChar ? '\\b' : '(?:$|\\s|[^\\w])'

  return new RegExp(`${leftBoundary}${escaped}${rightBoundary}`, 'i')
}

// Pre-compiled regex caches for performance
const COMPILED_TECH_REGEX = Object.entries(TECH_SKILLS).map(([alias, canonical]) => ({
  canonical,
  regex: buildPhraseRegex(alias)
}))

const COMPILED_HR_REGEX = Object.entries(HR_SKILLS).map(([alias, canonical]) => ({
  canonical,
  regex: buildPhraseRegex(alias)
}))

const COMPILED_FINANCE_REGEX = Object.entries(FINANCE_SKILLS).map(([alias, canonical]) => ({
  canonical,
  regex: buildPhraseRegex(alias)
}))

const COMPILED_ALL_REGEX = Object.entries(SKILL_ALIASES).map(([alias, canonical]) => ({
  canonical,
  regex: buildPhraseRegex(alias)
}))

/**
 * Extract canonical skills from raw text (candidate resume or generic text).
 */
export function extractSkills(text) {
  if (!text || typeof text !== 'string' || !text.trim()) {
    return []
  }

  const foundCanonicalSkills = new Set()

  for (const { canonical, regex } of COMPILED_ALL_REGEX) {
    if (regex.test(text)) {
      foundCanonicalSkills.add(canonical)
    }
  }

  return Array.from(foundCanonicalSkills)
}

/**
 * Domain-aware candidate skill extraction.
 * Guarantees that:
 * 1. An HR candidate extracts authentic HR & Administration skills (not polluted by deep IT tools).
 * 2. A Finance candidate extracts Finance & Accounting skills.
 * 3. A Tech candidate extracts core IT & Software engineering skills.
 */
export function extractCandidateSkills(text, domain = null) {
  if (!text || typeof text !== 'string' || !text.trim()) {
    return []
  }

  // 1. Candidate is in HR & Recruitment domain
  if (domain === DOMAINS.HR) {
    const found = new Set()
    for (const { canonical, regex } of COMPILED_HR_REGEX) {
      if (regex.test(text)) {
        found.add(canonical)
      }
    }
    // Also include general workplace/automation skills if present
    const allowedExtras = ['Process Automation', 'HR-Tech', 'ATS', 'Workday', 'BambooHR']
    for (const { canonical, regex } of COMPILED_ALL_REGEX) {
      if (allowedExtras.includes(canonical) && regex.test(text)) {
        found.add(canonical)
      }
    }
    if (found.size > 0) {
      return Array.from(found)
    }
  }

  // 2. Candidate is in Finance & Accounting domain
  if (domain === DOMAINS.FINANCE) {
    const found = new Set()
    for (const { canonical, regex } of COMPILED_FINANCE_REGEX) {
      if (regex.test(text)) {
        found.add(canonical)
      }
    }
    if (found.size > 0) {
      return Array.from(found)
    }
  }

  // 3. Candidate is in Tech / Engineering domain (Software, AI, Data, Cloud, Security, etc.)
  const foundTech = new Set()
  for (const { canonical, regex } of COMPILED_TECH_REGEX) {
    if (regex.test(text)) {
      foundTech.add(canonical)
    }
  }

  if (foundTech.size > 0) {
    return Array.from(foundTech)
  }

  // Fallback to all skills
  return extractSkills(text)
}

/**
 * Context-aware skill extraction for JOB POSTINGS.
 * CRITICAL RULE: If a job is a Tech/Engineering/Data/Cloud role, ignore boilerplate
 * HR operational terms (like "Human Resources" or "Onboarding") mentioned in the JD footer/company blurb.
 * Only extract HR skills if the job itself is an HR / Recruiter role!
 */
export function extractJobSkills(job) {
  if (!job) return []

  const title = String(job.title || '').trim()
  const fullText = [
    title,
    job.company || '',
    job.description || '',
    (job.tags || []).join(' ')
  ].join(' ')

  const isHrJobRole = /\b(recruiter|recruitment|talent acquisition|talent sourcing|human resources|hr manager|hr specialist|hr coordinator|people partner|talent partner)\b/i.test(title)

  const found = new Set()

  if (isHrJobRole) {
    // For HR roles, extract all skills (including HR and any technical keywords they recruit for)
    for (const { canonical, regex } of COMPILED_ALL_REGEX) {
      if (regex.test(fullText)) {
        found.add(canonical)
      }
    }
  } else {
    // For Tech / Engineering / Data roles, ONLY extract technical skills!
    // Never treat HR boilerplate ("contact HR", "our recruitment team") as a required tech skill of the job.
    for (const { canonical, regex } of COMPILED_TECH_REGEX) {
      if (regex.test(fullText)) {
        found.add(canonical)
      }
    }
  }

  return Array.from(found)
}

