/**
 * Detect domain from a job title.
 */
export function detectJobDomain(title = '') {
  const t = String(title).toLowerCase()

  if (/\b(recruiter|recruitment|talent acquisition|talent sourcing|human resources|hr manager|hr specialist|people operations|headhunter|talent partner)\b/i.test(t)) {
    return DOMAINS.HR
  }
  if (/\b(financial analyst|accountant|accounting|finance manager|auditor|cpa|bookkeeper|accounts payable|accounts receivable|treasury|tax manager)\b/i.test(t)) {
    return DOMAINS.FINANCE
  }
  if (/\b(solution architect|solutions architect|enterprise architect|cloud architect|data architect|software architect)\b/i.test(t)) {
    return DOMAINS.ARCHITECTURE
  }
  if (/\b(database administrator|dba|data engineer|data analyst|data science|bi developer|business intelligence|sql developer|oracle developer|database engineer|etl|big data|snowflake|redshift)\b/i.test(t)) {
    return DOMAINS.DATA
  }
  if (/\b(ai engineer|machine learning|ml engineer|deep learning|computer vision|nlp|generative ai|genai|llm|prompt engineer|applied scientist)\b/i.test(t)) {
    return DOMAINS.AI
  }
  if (/\b(devops|cloud engineer|sre|site reliability|infrastructure|kubernetes|terraform|aws engineer|azure engineer|sysadmin|systems administrator|linux engineer)\b/i.test(t)) {
    return DOMAINS.CLOUD_DEVOPS
  }
  if (/\b(cyber|security|infosec|soc analyst|siem|penetration tester|ethical hacker|iam|sailpoint)\b/i.test(t)) {
    return DOMAINS.SECURITY
  }
  if (/\b(qa engineer|qa analyst|quality assurance|software tester|automation tester|sdet|test automation)\b/i.test(t)) {
    return DOMAINS.QA
  }
  if (/\b(it support|desktop support|helpdesk|service desk|it technician|technical support)\b/i.test(t)) {
    return DOMAINS.IT_SUPPORT
  }
  if (/\b(software engineer|software developer|full stack|fullstack|frontend|front-end|backend|back-end|web developer|programmer|coder|mobile developer|ios developer|android developer|react developer|python developer|java developer|\.net developer|sailpoint developer)\b/i.test(t)) {
    return DOMAINS.SOFTWARE
  }

  return DOMAINS.OTHER
}

/**
 * Detect candidate's primary domain from resume text, file name, and extracted skills.
 * Guarantees that:
 * 1. Tech professionals (Software Developers, AI, Data, Cloud) who developed ERP finance/HR modules
 *    are NEVER misclassified as Finance or HR accountants.
 * 2. Dedicated HR candidates (Recruiters, HR Coordinators) are accurately classified as HR.
 * 3. Dedicated Finance candidates (Accountants, Financial Analysts) are accurately classified as Finance.
 */
export function detectCandidateDomain(candidateSkills = [], resumeText = '', fileName = '') {
  const combined = `${fileName} ${resumeText}`.toLowerCase()
  // Only look at the first 1500 chars for title/header classification
  const headerText = (resumeText || '').slice(0, 1500).toLowerCase()
  const fn = String(fileName || '').toLowerCase()

  // Pre-calculate skill counts across domains if not provided or empty
  let skills = candidateSkills
  if (!skills || skills.length === 0) {
    skills = extractSkills(resumeText)
  }

  const techCount = skills.filter(s => TECH_SKILL_NAMES.has(s)).length
  const hrCount = skills.filter(s => HR_SKILL_NAMES.has(s)).length
  const finCount = skills.filter(s => FINANCE_SKILL_NAMES.has(s)).length

  // Check explicit role title signals in header / top lines of resume
  const isTechTitle = /\b(software developer|software engineer|full stack|fullstack|frontend|front-end|backend|back-end|web developer|ai engineer|machine learning|data engineer|database administrator|dba|cloud engineer|devops|solutions architect|security engineer|programmer|coder|sdet|qa engineer|it support)\b/i.test(headerText)
  const isHrTitle = /\b(recruitment|recruiter|talent acquisition|human resources|hr manager|hr coordinator|hr specialist|hr administration|hr operations|talent sourcing|people operations)\b/i.test(headerText) || /hr_recruitment|recruitment_resume|recruiter_resume|\bhr\b/i.test(fn)
  const isFinanceTitle = /\b(financial analyst|accountant|accounting|finance manager|auditor|chartered accountant|cpa|bookkeeper|cost accountant|tax manager)\b/i.test(headerText) || /finance_resume|accounting_resume|accountant_resume|\bfinance\b/i.test(fn)

  // ── PRIORITY 1: Explicit tech title in resume header wins outright ──────────
  // A "Senior Software Developer" who built ERP finance modules is STILL a Software Developer!
  if (isTechTitle) {
    return _detectTechSubDomain(headerText, combined)
  }

  // ── PRIORITY 2: Strong tech skill count dominance ──────────────────────────
  // If candidate has 4+ tech skills and clearly outnumbers HR/Finance skills
  if (techCount >= 4 && techCount > hrCount * 2 && techCount > finCount * 2) {
    return _detectTechSubDomain(headerText, combined)
  }

  // ── PRIORITY 3: Explicit HR or Finance title in header ─────────────────────
  if (isHrTitle) return DOMAINS.HR
  if (isFinanceTitle) return DOMAINS.FINANCE

  // ── PRIORITY 4: HR/Finance skill density without tech title ───────────────
  if (hrCount >= 3 && hrCount >= techCount) return DOMAINS.HR
  if (finCount >= 3 && finCount > techCount) return DOMAINS.FINANCE

  // ── PRIORITY 5: Moderate tech skills ──────────────────────────────────────
  if (techCount >= 2 || /\b(developer|engineer|programmer|coder)\b/i.test(combined)) {
    return _detectTechSubDomain(headerText, combined)
  }

  // ── PRIORITY 6: Weaker HR/Finance signals ─────────────────────────────────
  if (hrCount >= 2) return DOMAINS.HR
  if (finCount >= 2) return DOMAINS.FINANCE

  return DOMAINS.OTHER
}

/** @internal Pick the specific tech sub-domain from the resume header */
function _detectTechSubDomain(headerText, combined) {
  // 1. Explicit software / full-stack / web developer title in header
  if (/\b(software engineer|software developer|full stack|fullstack|frontend|front-end|backend|back-end|web developer|programmer|coder|mobile developer|react developer|python developer|node developer|java developer|\.net developer|php developer|sailpoint developer)\b/i.test(headerText)) {
    return DOMAINS.SOFTWARE
  }

  // 2. Explicit AI / ML title in header
  if (/\b(ai engineer|machine learning|ml engineer|deep learning|nlp engineer|llm engineer|prompt engineer|generative ai specialist|genai engineer)\b/i.test(headerText)) {
    return DOMAINS.AI
  }

  // 3. Explicit Data title in header
  if (/\b(database administrator|dba|data engineer|data analyst|data scientist|big data|etl)\b/i.test(headerText)) {
    return DOMAINS.DATA
  }

  // 4. DevOps / Cloud
  if (/\b(devops|cloud engineer|sre|site reliability|infrastructure engineer|kubernetes|terraform)\b/i.test(headerText)) {
    return DOMAINS.CLOUD_DEVOPS
  }

  // 5. Security
  if (/\b(cybersecurity|security engineer|soc analyst|infosec|penetration tester|iam)\b/i.test(headerText)) {
    return DOMAINS.SECURITY
  }

  // 6. QA
  if (/\b(qa engineer|qa analyst|sdet|test automation|software tester)\b/i.test(headerText)) {
    return DOMAINS.QA
  }

  // 7. Solutions Architecture
  if (/\b(solutions architect|solution architect|enterprise architect|cloud architect)\b/i.test(headerText)) {
    return DOMAINS.ARCHITECTURE
  }
  if (/\b(it support|desktop support|helpdesk|service desk|technical support)\b/i.test(headerText)) {
    return DOMAINS.IT_SUPPORT
  }
  return DOMAINS.SOFTWARE
}
